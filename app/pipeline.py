"""Run orchestration: the pipelined brief -> storyboard -> judge -> film -> score -> final-cut loop.

One :class:`Run` owns the state of one ad (the exact JSON shape of CONTRACT §6), its :class:`EventBus`, its
run folder and every background task working on it. :class:`RunManager` owns all runs, loads finished runs
from disk on startup and is the single entry point used by the HTTP layer.

Scheduling is *pipelined, never barriered*::

    director ──┬──> music v1 (Lyria) ─────────────────────────────────────────────┐
               └──> anchor (NB2) ──┬──> s1: K variants ─> judge ─(repair)─> winner ─> Omni clip ─┤
                                   ├──> s2: K variants ─> judge ─(repair)─> winner ─> Omni clip ─┼─> final stitch
                                   └──> sN: ...                                                  ┘

Each scene is an independent chain, so scene 1 may already be rendering video while scene 4 is still being
judged. The final cut is produced as soon as every clip and the soundtrack have a version, and any later change
(new clip version, new music version, winner override) triggers a debounced, single-flight re-stitch.

Concurrency model
-----------------
* Everything runs on the single asyncio event loop; state mutations are therefore atomic between ``await``s.
* Every scene has two locks: ``board`` (storyboard rounds: initial, regenerate, restyle) and ``clip`` (Omni
  renders and edits). Operations on the *same* clip serialize (so multi-turn edits chain correctly) while
  different clips run fully in parallel. Global rate limiting lives in :class:`GenMedia`'s semaphores.
* Superseded work is coalesced with generation tokens: if the user picks three winners in quick succession only
  the last re-render actually runs; the same applies to music re-scores.
* Background work is started only through :meth:`Run.spawn`, which converts any exception into ``error`` +
  ``log`` events and a sensible status -- a failing model call can never crash the server.

Version bookkeeping: ``clip.current`` / ``music.current`` hold the ``v`` number (1-based) of the newest *done*
version (0 = none yet); ``final.version`` counts completed stitches.
"""

